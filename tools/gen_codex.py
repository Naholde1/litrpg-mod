def stage_entries():
    d = json.load(open(os.path.join(ROOT, 'litrpg_dungeon.json'), encoding='utf-8'))
    out = []
    for s in d['stages']:
        n = s['n']
        lo, hi = s['lvl']
        bosses = [b['type'].split(':')[1] for b in s['bosses']]
        names = ', '.join(BOSS_GUIDE[b][0] for b in bosses if b in BOSS_GUIDE)
        pages = [text(f"$(l)Уровни {lo}–{hi}.$()$(br2){STAGE_TEXT.get(n, '')}$(br2)$(l)Хранители:$() {names}.", s['name'])]
        for b in bosses:
            if b not in BOSS_GUIDE:
                continue
            title, guide = BOSS_GUIDE[b]
            pages.append(entity('litrpg:' + b, '', title, 0.45))
            pages.append(text(guide, title))
        out.append((f"stage{n}", f"{n}. {s['name']}", STAGE_ICON.get(n, 'minecraft:compass'), pages))
    return out


