TEMPER_RU = {'hostile': 'нападает сам', 'territorial': 'охраняет своё место', 'neutral': 'защищается', 'timid': 'убегает',
             'scavenger': 'добивает раненых'}


def bestiary_entries():
    from bestiary_data import SPECIES
    d = json.load(open(os.path.join(ROOT, 'litrpg_dungeon.json'), encoding='utf-8'))
    where = {}
    for s in d['stages']:
        for p in s['packs']:
            for m in p['mobs']:
                sid = m['type'].split(':')[1]
                where.setdefault(sid, set()).add(s['n'])
    out = [("about", "Твари подземелья", "minecraft:spider_eye", [
        text("Твари стоят отрядами на каждом этапе. Уровень у каждой — по её этапу, а ранг ($(b)★ элита$(), $(d)✦ чемпион$()) делает её крепче.$(br2)Ниже — те, кого Система видела в подземелье, и на каких этапах они встречаются."),
    ])]
    by_stage = {}
    for s in SPECIES:
        st = where.get(s['id'])
        if not st:
            continue
        by_stage.setdefault(min(st), []).append((s, st))
    names = {1: 'Склеп Забытых', 2: 'Паучья чаща', 3: 'Затопленный храм', 4: 'Кузни Пепла', 5: 'Шпиль Бездны'}
    for n in sorted(by_stage):
        pages = []
        for s, st in by_stage[n]:
            scale = round(min(1.0, 1.7 / max(s['w'], s['h'])), 2)
            stages = ', '.join(str(x) for x in sorted(st))
            pages.append(entity('litrpg:' + s['id'], f"Этапы: {stages}. {TEMPER_RU[s['temper']].capitalize()}.", s['ru'], scale))
            pages.append(text(s['desc'], s['ru']))
        out.append((f"stage{n}", f"Впервые: {names[n]}", "litrpg:" + by_stage[n][0][0]['id'] + "_spawn_egg", pages))
    return out


def main():
    general, by_role = class_entries()
    ENTRIES["classes"] = general
    ENTRIES["classes_tank"] = by_role['TANK']
    ENTRIES["classes_damage"] = by_role['DAMAGE']
    ENTRIES["classes_support"] = by_role['SUPPORT']
    ENTRIES["stages"] = stage_entries()
    ENTRIES["bestiary"] = bestiary_entries()
    if os.path.isdir(ASSETS):
        shutil.rmtree(ASSETS)
    os.makedirs(DATA, exist_ok=True)
    with open(os.path.join(DATA, 'book.json'), 'w', encoding='utf-8') as f:
        json.dump(BOOK, f, ensure_ascii=False, indent=2)
    total = 0
    for i, (cid, name, desc, icon) in enumerate(CATEGORIES):
        d = os.path.join(ASSETS, 'categories')
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, cid + '.json'), 'w', encoding='utf-8') as f:
            json.dump({"name": name, "description": desc, "icon": icon, "sortnum": i}, f, ensure_ascii=False, indent=2)
        for j, (eid, ename, eicon, pages) in enumerate(ENTRIES.get(cid, [])):
            d = os.path.join(ASSETS, 'entries', cid)
            os.makedirs(d, exist_ok=True)
            entry = {"name": ename, "icon": eicon, "category": "litrpg:" + cid, "sortnum": j, "pages": pages}
            with open(os.path.join(d, eid + '.json'), 'w', encoding='utf-8') as f:
                json.dump(entry, f, ensure_ascii=False, indent=2)
            total += 1
    print(f'codex generated: {len(CATEGORIES)} categories, {total} entries')


if __name__ == '__main__':
    main()
