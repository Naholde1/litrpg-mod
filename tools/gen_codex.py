def text(t, title=None):
    p = {"type": "patchouli:text", "text": t}
    if title:
        p["title"] = title
    return p


def spotlight(item, t, title=None):
    p = {"type": "patchouli:spotlight", "item": item, "text": t}
    if title:
        p["title"] = title
    return p


def entity(eid, t, name, scale=0.6):
    return {"type": "patchouli:entity", "entity": eid, "scale": scale, "name": name, "text": t}


