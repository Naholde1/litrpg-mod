    private static String pick(String[] a, RandomSource r) {
        return a[r.nextInt(a.length)];
    }

    /** Короткое имя (без фамилии) — для реплик и сюжетов. */
    public static String first(Race race, boolean female, RandomSource r) {
        return pick(switch (race) {
            case ELF -> female ? ELF_F : ELF_M;
            case DWARF -> female ? DWARF_F : DWARF_M;
            case ORC -> female ? ORC_F : ORC_M;
            case BEASTKIN -> female ? BEAST_F : BEAST_M;
            case DEMONKIN -> female ? DEMON_F : DEMON_M;
            default -> female ? HUMAN_F : HUMAN_M;
        }, r);
    }

    /** Полное имя: имя + фамилия, прозвище или род. */
    public static String full(Race race, boolean female, RandomSource r) {
        String n = first(race, female, r);
        float k = r.nextFloat();
        return switch (race) {
            case ELF -> k < 0.75f ? n + " " + pick(ELF_HOUSE, r) : n;
            case DWARF -> k < 0.45f ? n + (female ? ", дочь " : ", сын ") + pick(DWARF_M, r)
                    : k < 0.9f ? n + " из клана " + pick(DWARF_CLAN, r) : n;
            case ORC -> k < 0.7f ? n + " " + pick(ORC_EPI, r) : n;
            case BEASTKIN -> k < 0.4f ? n + " из стаи " + pick(BEAST_PACK, r) : n;
            case DEMONKIN -> k < 0.6f ? n + " " + pick(DEMON_EPI, r) : n;
            default -> k < 0.55f ? n + " " + pick(HUMAN_SUR, r) : k < 0.85f ? n + " " + pick(female ? HUMAN_EPI_F : HUMAN_EPI, r) : n;
        };
    }

    public static String pirate(RandomSource r) {
        return pick(HUMAN_M, r) + " " + pick(PIRATE_EPI, r);
    }
